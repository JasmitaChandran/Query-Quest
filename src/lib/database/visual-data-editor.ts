import type {
  SqlValue,
  TableDataEdit,
  TableSchema,
} from "@/lib/database/types";

export type VisualDraftRow = {
  key: string;
  rowId?: number;
  values: SqlValue[];
  original: SqlValue[];
  isNew: boolean;
};

export type VisualCellErrors = Record<string, string>;

export type VisualChangeSummary =
  | {
      type: "insert";
      rowKey: string;
      label: string;
      values: Array<{ column: string; value: SqlValue }>;
    }
  | {
      type: "update";
      rowKey: string;
      label: string;
      changes: Array<{ column: string; before: SqlValue; after: SqlValue }>;
    }
  | {
      type: "delete";
      rowKey: string;
      label: string;
    };

export type GridNavigationKey = "Enter" | "ArrowUp" | "ArrowDown" | "ArrowLeft" | "ArrowRight";

export function visualCellKey(rowKey: string, columnIndex: number) {
  return `${rowKey}:${columnIndex}`;
}

export function sameSqlValue(left: SqlValue, right: SqlValue) {
  return left instanceof Uint8Array && right instanceof Uint8Array
    ? left.length === right.length && left.every((value, index) => value === right[index])
    : left === right;
}

export function parseVisualCellValue(raw: string, declaredType: string): SqlValue {
  if (raw === "") return null;
  const type = declaredType.toUpperCase();
  if (type.includes("INT")) {
    const value = Number(raw);
    if (!Number.isSafeInteger(value)) throw new Error(`“${raw}” is not a valid integer.`);
    return value;
  }
  if (type.includes("REAL") || type.includes("FLOA") || type.includes("DOUB")) {
    const value = Number(raw);
    if (!Number.isFinite(value)) throw new Error(`“${raw}” is not a valid number.`);
    return value;
  }
  return raw;
}

export function buildVisualTableEdits(rows: VisualDraftRow[], deletedRowIds: ReadonlySet<number>): TableDataEdit[] {
  return [
    ...[...deletedRowIds].map((rowId) => ({ type: "delete" as const, rowId })),
    ...rows.flatMap((row): TableDataEdit[] => {
      if (row.rowId !== undefined && deletedRowIds.has(row.rowId)) return [];
      if (row.isNew) return [{ type: "insert", values: row.values }];
      return row.values.some((value, index) => !sameSqlValue(value, row.original[index]))
        ? [{ type: "update", rowId: row.rowId!, values: row.values }]
        : [];
    }),
  ];
}

function constraintKey(values: SqlValue[]) {
  if (values.some((value) => value === null)) return null;
  return JSON.stringify(values.map((value) => value instanceof Uint8Array ? [...value] : value));
}

function autoGeneratedPrimaryKey(schema: TableSchema, columnName: string) {
  const escaped = columnName.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
  return new RegExp(`(?:"${escaped}"|\\b${escaped}\\b)\\s+INTEGER\\s+PRIMARY\\s+KEY\\s+AUTOINCREMENT`, "i")
    .test(schema.createSql ?? "");
}

export function validateVisualDrafts(
  rows: VisualDraftRow[],
  schema: TableSchema,
  deletedRowIds: ReadonlySet<number>,
) {
  const errors: VisualCellErrors = {};
  const activeRows = rows.filter((row) => row.rowId === undefined || !deletedRowIds.has(row.rowId));

  for (const row of activeRows) {
    schema.columns.forEach((column, columnIndex) => {
      const value = row.values[columnIndex];
      if (value === null && column.notNull) {
        errors[visualCellKey(row.key, columnIndex)] = `${column.name} is required by its NOT NULL constraint.`;
      } else if (row.isNew && value === null && column.primaryKey && !autoGeneratedPrimaryKey(schema, column.name)) {
        errors[visualCellKey(row.key, columnIndex)] = `${column.name} needs a primary-key value.`;
      }
    });
  }

  const uniqueGroups = [
    schema.columns.filter((column) => column.primaryKey).map((column) => column.name),
    ...schema.indexes.filter((index) => index.unique).map((index) => index.columns),
  ].filter((columns) => columns.length > 0);

  for (const columns of uniqueGroups) {
    const indexes = columns.map((name) => schema.columns.findIndex((column) => column.name === name));
    if (indexes.some((index) => index < 0)) continue;
    const seen = new Map<string, string>();
    for (const row of activeRows) {
      const key = constraintKey(indexes.map((index) => row.values[index]));
      if (key === null) continue;
      const priorRowKey = seen.get(key);
      if (priorRowKey) {
        const label = columns.length === 1 ? `${columns[0]} must be unique.` : `${columns.join(" + ")} must be unique together.`;
        indexes.forEach((index) => {
          errors[visualCellKey(row.key, index)] = label;
          errors[visualCellKey(priorRowKey, index)] = label;
        });
      } else {
        seen.set(key, row.key);
      }
    }
  }

  return errors;
}

function displayValue(value: SqlValue) {
  if (value === null) return "NULL";
  if (value instanceof Uint8Array) return `BLOB (${value.byteLength} bytes)`;
  return String(value);
}

function rowLabel(row: VisualDraftRow, schema: TableSchema, fallbackIndex: number) {
  const primary = schema.columns
    .map((column, index) => ({ column, value: row.values[index] }))
    .filter(({ column }) => column.primaryKey && column.name);
  if (primary.length && primary.every(({ value }) => value !== null)) {
    return primary.map(({ column, value }) => `${column.name} ${displayValue(value)}`).join(" · ");
  }
  return row.isNew ? "New record" : `Row ${fallbackIndex + 1}`;
}

export function summarizeVisualChanges(
  rows: VisualDraftRow[],
  schema: TableSchema,
  deletedRowIds: ReadonlySet<number>,
): VisualChangeSummary[] {
  const summaries: VisualChangeSummary[] = [];
  rows.forEach((row, rowIndex) => {
    const label = rowLabel(row, schema, rowIndex);
    if (row.rowId !== undefined && deletedRowIds.has(row.rowId)) {
      summaries.push({ type: "delete", rowKey: row.key, label });
      return;
    }
    if (row.isNew) {
      summaries.push({
        type: "insert",
        rowKey: row.key,
        label,
        values: schema.columns.map((column, index) => ({ column: column.name, value: row.values[index] })),
      });
      return;
    }
    const changes = schema.columns.flatMap((column, index) => sameSqlValue(row.values[index], row.original[index])
      ? []
      : [{ column: column.name, before: row.original[index], after: row.values[index] }]);
    if (changes.length) summaries.push({ type: "update", rowKey: row.key, label, changes });
  });
  return summaries;
}

export function describeVisualEditError(error: unknown) {
  const raw = error instanceof Error ? error.message : String(error);
  const notNull = raw.match(/NOT NULL constraint failed:\s*[^.]+\.([^\s,]+)/i);
  if (notNull) return { message: `${notNull[1]} is required and cannot be NULL.`, columns: [notNull[1]] };
  const unique = raw.match(/UNIQUE constraint failed:\s*(.+)$/i);
  if (unique) {
    const columns = unique[1].split(",").map((part) => part.trim().split(".").at(-1) ?? part.trim());
    return { message: `${columns.join(" + ")} conflicts with an existing primary or unique value.`, columns };
  }
  if (/FOREIGN KEY constraint failed/i.test(raw)) {
    return { message: "A foreign-key value does not reference an existing record, or a referenced record is still in use.", columns: [] };
  }
  if (/CHECK constraint failed/i.test(raw)) {
    return { message: "A CHECK constraint rejected one or more pending values. Review the affected row and try again.", columns: [] };
  }
  if (/datatype mismatch|invalid|out of range/i.test(raw)) {
    return { message: `SQLite rejected a value: ${raw}`, columns: [] };
  }
  return { message: `The atomic batch was not saved. ${raw}`, columns: [] };
}

export function gridNavigationTarget(input: {
  key: GridNavigationKey;
  rowIndex: number;
  columnIndex: number;
  rowCount: number;
  columnCount: number;
  selectionStart: number | null;
  selectionEnd: number | null;
  valueLength: number;
}) {
  const { key, rowIndex, columnIndex, rowCount, columnCount, selectionStart, selectionEnd, valueLength } = input;
  if (key === "Enter" || key === "ArrowDown") return { rowIndex: Math.min(rowCount - 1, rowIndex + 1), columnIndex };
  if (key === "ArrowUp") return { rowIndex: Math.max(0, rowIndex - 1), columnIndex };
  if (key === "ArrowLeft" && selectionStart === 0 && selectionEnd === 0) {
    return { rowIndex, columnIndex: Math.max(0, columnIndex - 1) };
  }
  if (key === "ArrowRight" && selectionStart === valueLength && selectionEnd === valueLength) {
    return { rowIndex, columnIndex: Math.min(columnCount - 1, columnIndex + 1) };
  }
  return null;
}

export function parameterizedSqlPreview(
  statements: Array<{ sql: string; parameters: SqlValue[] | Record<string, SqlValue> }>,
) {
  return statements.map((statement) => `${statement.sql};\n-- bound parameters: ${JSON.stringify(statement.parameters)}`).join("\n\n");
}
